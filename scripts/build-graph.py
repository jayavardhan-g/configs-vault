SKIP = {"README.md", "CLAUDE.md", "cachyos/README.md", "Home.md", "KEYBINDS.md"}
SKIP_DIRS = {"files", "hubs", "entities", "scripts", "claude-memory"}
BEGIN, END = "<!-- graph:begin -->", "<!-- graph:end -->"
AUTO_BEGIN, AUTO_END = "<!-- auto:begin -->", "<!-- auto:end -->"
changed = []


def write(path, text):
    full = os.path.join(ROOT, path)
    old = open(full, encoding="utf-8").read() if os.path.exists(full) else None
    if old != text:
        changed.append(path)
        if not CHECK:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            open(full, "w", encoding="utf-8").write(text)


def entries():
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(x for x in dirs if not x.startswith(".") and x not in SKIP_DIRS)
        for f in sorted(files):
            p = os.path.relpath(os.path.join(d, f), ROOT)
            if f.endswith(".md") and p not in SKIP:
                yield p


def signal(text, path):
    title = next((l for l in text.splitlines() if l.startswith("# ")), "")
    ft = re.search(r"\*\*Files touched:\*\*.*", text)
    what = re.search(r"## What\s*\n(.+?)(\n## |\Z)", text, re.S)
    intro = text.split("\n## ", 1)[0][:1500]
    return " ".join([path, title, ft.group(0) if ft else "", what.group(1)[:800] if what else "", intro])


def strip_graph(text):
    # remove the block plus the blank line insert_graph puts after it
    return re.sub(rf"{re.escape(BEGIN)}.*?{re.escape(END)}\n\n?", "", text, flags=re.S)


def link_line(names):
    return f"{BEGIN}\n**Graph:** " + " · ".join(f"[[{n}]]" for n in names) + f"\n{END}\n"


def insert_graph(text, names):
    text = strip_graph(text)
    if not names:
        return text
    lines = text.split("\n")
    # after the metadata block (**Date/Category/Files touched**) if present, else after the H1
    idx = next((i for i, l in enumerate(lines) if l.startswith("# ")), -1) + 1
    j = idx
    while j < len(lines) and (lines[j].strip() == "" or lines[j].startswith("**")) and j < idx + 8:
        if lines[j].startswith("**"):
            idx = j + 1
        j += 1
    before = "\n".join(lines[:idx]).rstrip("\n")
    after = "\n".join(lines[idx:]).lstrip("\n")
    return f"{before}\n\n{link_line(names)}\n{after}"


def with_auto(path, manual_default, auto):
    full = os.path.join(ROOT, path)
    if os.path.exists(full):
        text = open(full, encoding="utf-8").read()
        if AUTO_BEGIN in text:
            pre, rest = text.split(AUTO_BEGIN, 1)
            post = rest.split(AUTO_END, 1)[1] if AUTO_END in rest else ""
            return f"{pre}{AUTO_BEGIN}\n{auto}{AUTO_END}{post}"
    return f"{manual_default}\n{AUTO_BEGIN}\n{auto}{AUTO_END}\n"


def main():
    titles, by_entity = {}, {n: [] for n in ENTITIES}
    for p in entries():
        text = open(os.path.join(ROOT, p), encoding="utf-8").read()
        titles[p] = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), p)
        sig = signal(strip_graph(text), p)
        names = [n for n, e in ENTITIES.items()
                 if re.search(e["match"], sig, re.I | re.M) or p in e.get("extra", [])]
        for n in names:
            by_entity[n].append(p)
        write(p, insert_graph(text, names))

    mem_dir = os.path.join(ROOT, "claude-memory")
    if os.path.isdir(mem_dir):
        for f in sorted(os.listdir(mem_dir)):
            if f.endswith(".md") and f != "MEMORY.md":
                p = f"claude-memory/{f}"
                text = open(os.path.join(ROOT, p), encoding="utf-8").read()
                names = [n for n, e in ENTITIES.items() if re.search(e["match"], strip_graph(text), re.I | re.M)]
                body = strip_graph(text).rstrip("\n")
                write(p, body + ("\n\n" + link_line(names) if names else "\n"))

    for n, e in ENTITIES.items():
        manual = (f"---\ntype: entity\nhub: \"[[{e['hub']}]]\"\n---\n# {n}\n\n{e['summary']}\n\n"
                  f"**Hub:** [[{e['hub']}]]\n")
        if e.get("config"):
            manual += f"**Config:** {e['config']}\n"
        if e["related"]:
            manual += "**Related:** " + " · ".join(f"[[{r}]]" for r in e["related"]) + "\n"
        auto = "## Entries\n\n" + "".join(
            f"- [[{os.path.splitext(os.path.basename(p))[0] if sum(os.path.basename(q) == os.path.basename(p) for q in titles) == 1 else os.path.splitext(p)[0]}|{titles[p]}]]\n"
            for p in sorted(by_entity[n])) if by_entity[n] else "## Entries\n\n(none yet)\n"
        write(f"entities/{n}.md", with_auto(f"entities/{n}.md", manual, auto))

    for h, desc in HUBS.items():
        manual = f"---\ntype: hub\n---\n# {h}\n\n{desc}\n\nBack to [[Home]].\n"
        ents = [n for n, e in ENTITIES.items() if e["hub"] == h]
        auto = "## Entities\n\n" + "".join(
            f"- [[{n}]] — {ENTITIES[n]['summary'].split('. ')[0].rstrip('.')} ({len(by_entity[n])} entries)\n"
            for n in ents)
        write(f"hubs/{h}.md", with_auto(f"hubs/{h}.md", manual, auto))

    unlinked = [p for p in titles if not any(p in v for v in by_entity.values())]
    print(f"{len(titles)} entries, {len(ENTITIES)} entities, {len(HUBS)} hubs; "
          f"{len(changed)} file(s) {'stale' if CHECK else 'written'}")
    if unlinked:
        print("entries with no entity:", ", ".join(unlinked))
    if CHECK and changed:
        print("\n".join("  " + c for c in changed))
        sys.exit(1)


main()
